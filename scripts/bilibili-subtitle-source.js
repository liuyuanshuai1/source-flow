(async () => {
  const state = window.__INITIAL_STATE__ || {};
  const video = state.videoData || {};
  const aid = video.aid || state.aid;
  const cid = video.cid || state.cid;
  const bvid = video.bvid || state.bvid || location.pathname.match(/BV[0-9A-Za-z]+/)?.[0];
  const base = {
    platform: "bilibili",
    bvid,
    aid,
    cid,
    pubdate: video.pubdate || null,
    duration: video.duration || null,
    owner: video.owner ? { mid: video.owner.mid, name: video.owner.name } : null,
    url: `https://www.bilibili.com/video/${bvid}/`,
    title: document.title,
    fetched_at: new Date().toISOString(),
  };

  if (!aid || !cid || !bvid) {
    return JSON.stringify({ ...base, status: "page_not_ready" });
  }

  // Reuse the signed URL generated by the video player. Never include it in output.
  const playerUrls = performance.getEntriesByType("resource")
    .map((entry) => entry.name)
    .filter((name) => {
      try {
        const url = new URL(name);
        return url.hostname === "api.bilibili.com" &&
          url.pathname === "/x/player/wbi/v2" &&
          url.searchParams.get("aid") === String(aid) &&
          url.searchParams.get("cid") === String(cid) &&
          url.searchParams.has("w_rid");
      } catch {
        return false;
      }
    });

  if (playerUrls.length === 0) {
    return JSON.stringify({ ...base, status: "signed_player_request_missing" });
  }

  try {
    const playerResponse = await fetch(playerUrls.at(-1), { credentials: "include" });
    const player = await playerResponse.json();
    if (!playerResponse.ok || player.code !== 0) {
      return JSON.stringify({ ...base, status: "player_error", http_status: playerResponse.status, api_code: player.code });
    }

    const tracks = player.data?.subtitle?.subtitles || [];
    const track = tracks.find((item) => item.lan === "ai-zh") ||
      tracks.find((item) => item.lan?.startsWith("zh"));
    if (!track?.subtitle_url) {
      return JSON.stringify({ ...base, status: tracks.length ? "chinese_subtitle_missing" : "no_subtitle", available_languages: tracks.map((item) => item.lan) });
    }

    const subtitleUrl = track.subtitle_url.startsWith("//")
      ? `https:${track.subtitle_url}`
      : track.subtitle_url;
    const subtitleResponse = await fetch(subtitleUrl, { credentials: "omit" });
    const subtitle = await subtitleResponse.json();
    if (!subtitleResponse.ok || !Array.isArray(subtitle.body) || subtitle.body.length === 0) {
      return JSON.stringify({ ...base, status: "subtitle_error", http_status: subtitleResponse.status });
    }

    const segments = subtitle.body.map(({ from, to, content }) => ({ from, to, content }));
    return JSON.stringify({
      ...base,
      status: "ok",
      source_type: "player_subtitle",
      language: track.lan,
      language_label: track.lan_doc,
      segment_count: segments.length,
      segments,
      transcript: segments.map((item) => item.content).join("\n"),
    });
  } catch (error) {
    return JSON.stringify({ ...base, status: "fetch_error", error: String(error) });
  }
})()
